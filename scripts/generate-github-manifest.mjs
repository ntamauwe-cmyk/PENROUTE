/**
 * Generates the project manifest used by the GitHub sync feature:
 *   bun run github:manifest
 *
 * Walks the project (respecting .gitignore-equivalent exclusions), returns
 * every file that should be committed to the existing GitHub repository,
 * with base64-encoded content (GitHub Git Data API format) and sha256
 * fingerprints for change detection.
 *
 * Output: src/lib/github-manifest.generated.ts
 */
import { createHash } from "node:crypto";
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";

const ROOT = process.cwd();

// Mirrors .gitignore — these are never committed (spec: no secrets, no build
// output, no generated code in the GitHub repo).
const EXCLUDED_DIRS = new Set([
  "node_modules",
  "dist",
  "build",
  ".vite",
  ".git",
  ".convex",
  ".turbo",
  "coverage",
  ".idea",
  ".vscode",
  "__pycache__",
]);
const EXCLUDED_FILES = new Set([".env", ".env.local", "package-lock.json", "yarn.lock", "pnpm-lock.yaml"]);
const EXCLUDED_SUFFIXES = [".log", ".tmp", ".bak", ".pem", ".key"];

/** Secret content guard — refuses to ship anything that looks like a credential. */
const SECRET_PATTERNS = [
  /sk_live_[A-Za-z0-9]{16,}/,
  /sk_test_[A-Za-z0-9]{16,}/,
  /ghp_[A-Za-z0-9]{36,}/,
  /gho_[A-Za-z0-9]{36,}/,
  /github_pat_[A-Za-z0-9_]{22,}/,
  /-----BEGIN (RSA |EC |OPENSSH )?PRIVATE KEY-----/,
  /AKIA[0-9A-Z]{16}/,
];
function containsSecret(text) {
  return SECRET_PATTERNS.some((re) => re.test(text));
}

function walk(dir, out = []) {
  for (const name of readdirSync(dir).sort()) {
    const full = join(dir, name);
    const rel = relative(ROOT, full).split(sep).join("/");
    const st = statSync(full);
    if (st.isDirectory()) {
      if (!EXCLUDED_DIRS.has(name)) walk(full, out);
      continue;
    }
    if (EXCLUDED_FILES.has(rel) || EXCLUDED_FILES.has(name)) continue;
    // Never ship env files — only the sanitised .env.example template is safe.
    if (name.startsWith(".env") && rel !== ".env.example") continue;
    if (EXCLUDED_SUFFIXES.some((s) => name.endsWith(s))) continue;
    out.push(rel);
  }
  return out;
}

const files = [];
for (const rel of walk(ROOT)) {
  // Skip previously generated manifest to avoid self-reference bloat
  if (rel === "src/lib/github-manifest.generated.ts") continue;
  const buf = readFileSync(join(ROOT, rel));
  const text = buf.toString("utf8");
  if (containsSecret(text)) {
    console.error(`REFUSING to include possible secret in ${rel} — fix and regenerate.`);
    process.exit(1);
  }
  files.push({
    path: rel,
    contentBase64: buf.toString("base64"),
    sha256: createHash("sha256").update(buf).digest("hex"),
    bytes: buf.length,
  });
}

const header = `// AUTO-GENERATED by scripts/generate-github-manifest.mjs — do not edit by hand.
// Regenerate with: bun run github:manifest
export const MANIFEST_GENERATED_AT = ${Date.now()};
export const MANIFEST_TOTAL_BYTES = ${files.reduce((s, f) => s + f.bytes, 0)};
export const GITHUB_MANIFEST: { path: string; contentBase64: string; sha256: string; bytes: number }[] = ${JSON.stringify(
  files,
  null,
  1,
).replace(/"([a-zA-Z_][a-zA-Z0-9_]*)":/g, "$1:")};
`;

writeFileSync(join(ROOT, "src/lib/github-manifest.generated.ts"), header, "utf8");
console.log(`Manifest written: ${files.length} files, ${files.reduce((s, f) => s + f.bytes, 0)} bytes`);
